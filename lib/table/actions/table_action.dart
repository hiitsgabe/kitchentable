import 'package:flutter/foundation.dart';

/// Everything that can happen at this table.
///
/// Eleven, from the spec, and the list is closed on purpose: a sealed type
/// means the reducer cannot quietly forget one, and a twelfth verb has to be
/// argued for rather than added.
///
/// Every one of them is a value, and equality is its fields rather than its
/// identity. That is what the wire needs: a verb that came off a wire is a
/// different object from the one that went on, and a table that compares them
/// by identity cannot tell a faithful round trip from a lossy one.
@immutable
sealed class TableAction {
  const TableAction();
}

/// Moves a card from wherever it is into a pile.
class MoveCard extends TableAction {
  const MoveCard({
    required this.cardId,
    required this.toZoneId,
    this.at,
    this.faceDown,
    this.position,
  });

  final String cardId;
  final String toZoneId;

  /// Where in an ordered pile. Null means the top.
  final int? at;

  /// Null leaves it as it was. Moving to a hand does not turn a card over by
  /// itself, because the table does not know that hands are private: the zone
  /// does, and the screen reads the zone.
  final bool? faceDown;

  final ({double x, double y})? position;

  @override
  bool operator ==(Object other) =>
      other is MoveCard &&
      other.cardId == cardId &&
      other.toZoneId == toZoneId &&
      other.at == at &&
      other.faceDown == faceDown &&
      other.position == position;

  @override
  int get hashCode => Object.hash(cardId, toZoneId, at, faceDown, position);
}

/// Turns a card. With no angle it is a toggle, straight to turned and back,
/// which is the tap. With one it sets that angle, which is the menu.
class RotateCard extends TableAction {
  const RotateCard(this.cardId, {this.to});
  final String cardId;
  final int? to;

  @override
  bool operator ==(Object other) =>
      other is RotateCard &&
      other.cardId == cardId &&
      other.to == to;

  @override
  int get hashCode => Object.hash(cardId, to);
}

