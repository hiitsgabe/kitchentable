class CreateToken extends TableAction {
  const CreateToken({
    required this.zoneId,
    required this.oracleId,
    required this.cardId,
  });

  final String zoneId;
  final String oracleId;

  /// Generated by the caller rather than inside the reducer, so applying the
  /// same action twice gives the same table. Plan 3 replays these.
  final String cardId;

  @override
  bool operator ==(Object other) =>
      other is CreateToken &&
      other.zoneId == zoneId &&
      other.oracleId == oracleId &&
      other.cardId == cardId;

  @override
  int get hashCode => Object.hash(zoneId, oracleId, cardId);
}

