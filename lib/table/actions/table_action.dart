class AttachCard extends TableAction {
  const AttachCard({required this.cardId, required this.toCardId});

  final String cardId;

  /// Null detaches.
  final String? toCardId;

  @override
  bool operator ==(Object other) =>
      other is AttachCard &&
      other.cardId == cardId &&
      other.toCardId == toCardId;

  @override
  int get hashCode => Object.hash(cardId, toCardId);
